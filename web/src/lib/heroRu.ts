/** Имя героя по-русски и род: f — женский (знак ~ в таблице). */
export function heroRu(id: number | null | undefined, heroes?: Map<number, Hero>): { name: string; f: boolean } {
  const raw = id ? RU[id] : undefined;
  if (!raw) return { name: (id ? heroes?.get(id)?.name : null) ?? "враг", f: false };
  return { name: raw.replace("~", ""), f: raw.endsWith("~") };
}

/** Глагол прошедшего времени в нужном роде: v(hero, "убил", "убила"). */
export const v = (h: { f: boolean }, m: string, f: string) => (h.f ? f : m);
