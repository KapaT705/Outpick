// Отрезки игры одними словами во всей программе: линия до 10-й минуты, мидгейм до 20-й, дальше лейт.
// Без импортов, чтобы подпись можно было использовать и на клиенте (lib/report.ts тянет за собой node:fs).

/** Подпись отрезка игры: «0-10 мин · линия», «20+ мин · лейт». */
export const phaseLabel = (from: number, to: number | null) => `${to == null ? `${from}+` : `${from}-${to}`} мин · ${from === 0 ? "линия" : from === 10 ? "мидгейм" : "лейт"}`;
